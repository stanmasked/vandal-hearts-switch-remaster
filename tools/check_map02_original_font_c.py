#!/usr/bin/env python3
"""Independently reconstruct the private original US BIOS-font C bytes.

Only for a locally owned PsyQ KROMDAT.BIN or PS1 BIOS. Reconstructs the
exact public upstream 209-glyph C serialization without executing a mutable
generator path. No original font bytes, per-file digests or paths are emitted.
A successful comparison is NOT evidence of executed gameplay or MAP02 art.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat

from tools.check_map02_cycle_make_plan import BUILD, preflight
from tools.check_map02_private_pc_inputs import (
    BIOS_SIZE, FONT_BIOS_OFFSET, FONT_LENGTH, US_FONT_SHA256,
)

NAME = "map02_pinned_kanji_font.c"
MAX_SOURCE = 128 * 1024


def _identity(st):
    return (st.st_dev, st.st_ino, st.st_uid, st.st_mode, st.st_nlink,
            st.st_size, st.st_mtime_ns, st.st_ctime_ns)


def _read_owned(path, category, *, length_limit, exact_mode=None):
    path = Path(path)
    if path.is_symlink():
        raise ValueError("linked private original input: " + category)
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except OSError:
        raise ValueError("private original input unavailable: " + category) from None
    with os.fdopen(fd, "rb") as stream:
        before = os.fstat(stream.fileno())
        if (not stat.S_ISREG(before.st_mode)
                or before.st_uid != os.geteuid()
                or before.st_nlink != 1
                or not (0 < before.st_size <= length_limit)
                or (exact_mode is not None and
                    stat.S_IMODE(before.st_mode) != exact_mode)):
            raise ValueError("private original input metadata invalid: " + category)
        data = stream.read(length_limit + 1)
        try:
            after = os.stat(path, follow_symlinks=False)
        except OSError:
            raise ValueError("private original input changed: " + category) from None
        if (len(data) != before.st_size or
                _identity(os.fstat(stream.fileno())) != _identity(before) or
                _identity(after) != _identity(before)):
            raise ValueError("private original input changed: " + category)
        return data, _identity(before)


def _expected_us_font_c(glyphs):
    if len(glyphs) != FONT_LENGTH:
        raise ValueError("private original US font length mismatch")
    lines = [
        "/* GENERATED by platform/pc/tools/gen_kanji_font.py -- do not edit by hand. */",
        "/* PS1 BIOS kanji ROM glyphs (16x15 1bpp, 30 bytes each), 209 glyphs",
        " * (us region), sourced from PsyQ KROMDAT.BIN. Fetched by Krom2RawAdd",
        " * (libkernel.c) for the game's DrawSjisGlyph(). See the generator header. */",
        "",
        f"const unsigned char pc_kanji_charset2[{FONT_LENGTH}] = {{",
    ]
    for start in range(0, FONT_LENGTH, 15):
        lines.append("    " + "".join(
            f"0x{byte:02x}," for byte in glyphs[start:start + 15]))
    lines += ["};", ""]
    return "\n".join(lines).encode("utf-8")


def verify_generated_original_font(upstream, bundle, *, krom_source=None):
    upstream = Path(upstream).absolute()
    preflight(upstream, bundle)
    source = (Path(krom_source).absolute() if krom_source is not None else
              upstream / "external/psy-q/3.6/PSYQ/BIN/KROMDAT.BIN")
    blob, source_identity = _read_owned(
        source, "owned KROM/BIOS", length_limit=BIOS_SIZE)
    glyphs = blob[FONT_BIOS_OFFSET:FONT_BIOS_OFFSET + FONT_LENGTH] if (
        len(blob) == BIOS_SIZE) else blob[:FONT_LENGTH]
    if (len(glyphs) != FONT_LENGTH or
            hashlib.sha256(glyphs).hexdigest() != US_FONT_SHA256):
        raise ValueError("original US BIOS font charset differs from pinned source")
    generated_path = upstream / "platform/pc" / BUILD / NAME
    generated, generated_identity = _read_owned(
        generated_path, "generated private font C",
        length_limit=MAX_SOURCE, exact_mode=0o600)
    if generated != _expected_us_font_c(glyphs):
        raise ValueError("generated private font C differs from original US KROM")
    # Recheck both names after the independent comparison so a same-byte
    # replacement after the first read cannot silently pass.
    for path, category, expected_bytes, expected_identity, maximum, mode in (
        (source, "owned KROM/BIOS", blob, source_identity, BIOS_SIZE, None),
        (generated_path, "generated private font C", generated,
         generated_identity, MAX_SOURCE, 0o600),
    ):
        # The second read verifies data AND metadata. Identity-only checks
        # could miss same-inode writes on filesystems with weak timestamps.
        fresh_bytes, current = _read_owned(
            path, category, length_limit=maximum, exact_mode=mode)
        if current != expected_identity or fresh_bytes != expected_bytes:
            raise ValueError("private original input changed: " + category)
    preflight(upstream, bundle)
    return {
        "schema": "vh.map02.original-us-font-c-provenance.v1",
        "pinned_original_krom_font_c_identical": True,
        "original_font_bytes_disclosed": False,
        "actual_gameplay_executed": False,
        "original_map02_rendering_proven": False,
    }



def verify_linked_original_font(upstream, bundle, binary, *, krom_source=None):
    """Bind the independently checked generated C to the actual linked ELF.

    Neither the expected glyph bytes nor the ELF's extracted bytes leave this
    process. The ELF inspector independently locates the genuine read-only,
    allocated object symbol and verifies its bytes in a file-backed PT_LOAD.
    """
    verify_generated_original_font(upstream, bundle, krom_source=krom_source)
    upstream = Path(upstream).absolute()
    source = (Path(krom_source).absolute() if krom_source is not None else
              upstream / "external/psy-q/3.6/PSYQ/BIN/KROMDAT.BIN")
    blob, identity = _read_owned(
        source, "owned KROM/BIOS", length_limit=BIOS_SIZE)
    glyphs = blob[FONT_BIOS_OFFSET:FONT_BIOS_OFFSET + FONT_LENGTH] if (
        len(blob) == BIOS_SIZE) else blob[:FONT_LENGTH]
    if (len(glyphs) != FONT_LENGTH or
            hashlib.sha256(glyphs).hexdigest() != US_FONT_SHA256):
        raise ValueError("original US BIOS font charset differs from pinned source")
    from tools.check_map02_linked_font_elf import check_linked_font_bytes
    check_linked_font_bytes(binary, glyphs)
    same, verified_identity = _read_owned(
        source, "owned KROM/BIOS", length_limit=BIOS_SIZE)
    if same != blob or verified_identity != identity:
        raise ValueError("owned KROM changed during ELF comparison")
    preflight(upstream, bundle)
    return {
        "schema": "vh.map02.original-us-linked-font-provenance.v1",
        "linked_original_us_font_bytes_match": True,
        "original_font_bytes_disclosed": False,
        "actual_gameplay_executed": False,
        "original_map02_rendering_proven": False,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pinned_original_pc_checkout", type=Path)
    parser.add_argument("private_prepared_bundle", type=Path)
    parser.add_argument("--krom-source", type=Path)
    args = parser.parse_args()
    try:
        result = verify_generated_original_font(
            args.pinned_original_pc_checkout, args.private_prepared_bundle,
            krom_source=args.krom_source)
    except ValueError as exc:
        parser.error(str(exc))
    except OSError:
        parser.error("private original font verification failed")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
