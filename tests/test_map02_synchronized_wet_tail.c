/* MAP02 A-selection -> silent second cue: exact-clock wet-tail causality.
 * No original game/SEQ/VAB assets, no guest scheduling assumptions.
 */
#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "platform_input.h"
#include "vh_game_music_mailbox.h"
#include "vh_music_scene.h"

#define HDR 'p','Q','E','S',0,0,0,0,1,0xe0,7,0xa1,0x20,0,0
#define PRE_BLOCKS 64u
#define TAIL_BLOCKS 48u

/* An audible repeating note; then a valid cue with NO note-on events.
 * The delayed end-of-track event prevents an empty-loop parse failure. */
static const uint8_t field_seq[] = {
    HDR, 0,0xc0,7, 0,0x90,60,100,
    0x87,0x68,0x80,60,0,0,0xff,0x2f
};
static const uint8_t selected_seq[] = {
    HDR, 0,0xc0,9, 0x87,0x68,0xff,0x2f
};

static int16_t tone_pcm[128];
static VhNativeSpu wet_spu, reset_spu;
static VhMusicScene wet_scene, reset_scene;
static int16_t wet_pcm[VH_AUDIO_BLOCK_FRAMES * 2u];
static int16_t reset_pcm[VH_AUDIO_BLOCK_FRAMES * 2u];

typedef struct {
    uint64_t initial_hash;
    uint64_t retained_hash;
    uint64_t reset_hash;
    unsigned different_blocks;
    unsigned retained_nonzero;
    unsigned reset_nonzero;
} Result;

static uint64_t hash_samples(uint64_t h, const int16_t *values, size_t n) {
    for(size_t i=0;i<n;i++) {
        const uint16_t v=(uint16_t)values[i];
        h=(h ^ (uint8_t)v)*UINT64_C(1099511628211);
        h=(h ^ (uint8_t)(v>>8))*UINT64_C(1099511628211);
    }
    return h;
}

static int resolve(void *ctx, unsigned program, unsigned note,
                   unsigned velocity, unsigned volume, unsigned pan,
                   VhSeqTone *tone) {
    (void)ctx; (void)velocity; (void)volume; (void)pan;
    if(program!=7u || note!=60u) return -1;
    memset(tone,0,sizeof *tone);
    tone->pcm=tone_pcm;
    tone->frames=128u;
    tone->loop_start=0u;
    tone->loop_end=128u;
    tone->pitch_step=4096u;
    tone->adsr1=15u;
    tone->gain_left=0.75f;
    tone->gain_right=0.4f;
    tone->reverb_send=1;
    return 0;
}

static unsigned count_nonzero(const int16_t *pcm) {
    unsigned n=0;
    for(unsigned i=0;i<VH_AUDIO_BLOCK_FRAMES * 2u;i++)
        n+=pcm[i]!=0;
    return n;
}

static void reset_both(void) {
    for(unsigned i=0;i<128u;i++)
        tone_pcm[i]=(int16_t)(11000+(int)i*17);
    vh_native_spu_reset(&wet_spu);
    vh_native_spu_reset(&reset_spu);
    assert(vh_native_spu_set_interpolation(&wet_spu,VH_SPU_GAUSSIAN)==0);
    assert(vh_native_spu_set_interpolation(&reset_spu,VH_SPU_GAUSSIAN)==0);
    assert(vh_native_spu_set_reverb(&wet_spu,1,0.5f)==0);
    assert(vh_native_spu_set_reverb(&reset_spu,1,0.5f)==0);
    vh_music_scene_init(&wet_scene,&wet_spu);
    vh_music_scene_init(&reset_scene,&reset_spu);
    assert(vh_music_scene_set_reverb_continuity(&wet_scene,1)==0);
    assert(!reset_scene.keep_reverb_across_cues);
}

static Result trial(void) {
    reset_both();
    Result result={
        UINT64_C(14695981039346656037),
        UINT64_C(14695981039346656037),
        UINT64_C(14695981039346656037),
        0u,0u,0u
    };
    VhGameState state={1,2,1,2,6,3,0};
    const unsigned first_scene=vh_game_music_for_state(&state);
    assert(first_scene==VH_GAME_MUSIC_FIELD);
    const VhMusicCue field={
        first_scene+1u,field_seq,sizeof field_seq,0u,resolve,NULL
    };
    const VhMusicCue selected={
        VH_GAME_MUSIC_HERO_SELECTED+1u,selected_seq,sizeof selected_seq,
        0u,resolve,NULL
    };
    assert(vh_music_scene_request(&wet_scene,&field,0u)==0);
    assert(vh_music_scene_request(&reset_scene,&field,0u)==0);
    for(unsigned block=0;block<PRE_BLOCKS;block++) {
        assert(vh_music_scene_render(&wet_scene,wet_pcm)==0);
        assert(vh_music_scene_render(&reset_scene,reset_pcm)==0);
        assert(!memcmp(wet_pcm,reset_pcm,sizeof wet_pcm));
        result.initial_hash=hash_samples(result.initial_hash,wet_pcm,
                                        VH_AUDIO_BLOCK_FRAMES*2u);
    }
    assert(wet_scene.seq.note_ons==1u &&
           reset_scene.seq.note_ons==1u);
    assert(wet_spu.reverb.cursor==reset_spu.reverb.cursor);
    assert(!memcmp(&wet_spu.reverb,&reset_spu.reverb,
                   sizeof wet_spu.reverb));

    /* A selection is generated by the SAME MAP02 input contract as main.c. */
    const unsigned before=vh_game_music_for_state(&state);
    assert(vh_process_input(&state,VH_INPUT_CONFIRM,8,6,2)==0);
    const unsigned after=vh_game_music_for_state(&state);
    assert(before==VH_GAME_MUSIC_FIELD &&
           after==VH_GAME_MUSIC_HERO_SELECTED && after!=before);
    assert(vh_music_scene_request(&wet_scene,&selected,0u)==0);
    assert(vh_music_scene_request(&reset_scene,&selected,0u)==0);
    assert(wet_scene.active.id==reset_scene.active.id);
    assert(wet_scene.seq.note_ons==0u &&
           reset_scene.seq.note_ons==0u);
    for(unsigned i=0;i<VH_NATIVE_MUSIC_VOICES;i++) {
        assert(!wet_spu.voice[i].active && !reset_spu.voice[i].active);
        assert(wet_spu.voice[i].pcm!=tone_pcm);
        assert(reset_spu.voice[i].pcm!=tone_pcm);
    }
    assert(memcmp(&wet_spu.reverb,&reset_spu.reverb,
                  sizeof wet_spu.reverb)!=0);
    for(unsigned block=0;block<TAIL_BLOCKS;block++) {
        assert(vh_music_scene_render(&wet_scene,wet_pcm)==0);
        assert(vh_music_scene_render(&reset_scene,reset_pcm)==0);
        result.retained_nonzero+=count_nonzero(wet_pcm);
        result.reset_nonzero+=count_nonzero(reset_pcm);
        result.different_blocks+=memcmp(wet_pcm,reset_pcm,sizeof wet_pcm)!=0;
        result.retained_hash=hash_samples(result.retained_hash,wet_pcm,
                                         VH_AUDIO_BLOCK_FRAMES*2u);
        result.reset_hash=hash_samples(result.reset_hash,reset_pcm,
                                      VH_AUDIO_BLOCK_FRAMES*2u);
        assert(wet_scene.stage==reset_scene.stage);
        assert(wet_scene.blocks_rendered==reset_scene.blocks_rendered);
        assert(wet_scene.seq.note_ons==0u && reset_scene.seq.note_ons==0u);
        assert(wet_scene.seq.note_offs==reset_scene.seq.note_offs);
        assert(wet_scene.seq.blocks_advanced==reset_scene.seq.blocks_advanced);
    }
    assert(result.reset_nonzero==0u);
    assert(result.retained_nonzero>0u);
    assert(result.different_blocks>0u);
    assert(result.retained_hash!=result.reset_hash);
    /* Even if wet history is preserved across non-silent cues,
     * explicit silence clears both reverb histories. */
    assert(vh_music_scene_request(&wet_scene,NULL,0u)==0);
    assert(vh_music_scene_request(&reset_scene,NULL,0u)==0);
    assert(vh_music_scene_render(&wet_scene,wet_pcm)==0);
    assert(vh_music_scene_render(&reset_scene,reset_pcm)==0);
    assert(!count_nonzero(wet_pcm) && !count_nonzero(reset_pcm));
    for(unsigned i=0;i<VH_REV_SAMPLES;i++) {
        assert(wet_spu.reverb.work[i]==0);
        assert(reset_spu.reverb.work[i]==0);
    }
    assert(vh_music_scene_detach(&wet_scene)==0);
    assert(vh_music_scene_detach(&reset_scene)==0);
    return result;
}

int main(void) {
    const Result first=trial();
    const Result second=trial();
    assert(!memcmp(&first,&second,sizeof first));
    printf("MAP02 synchronized STUDIO_C: PASS "
           "initial=%016llx wet=%016llx reset=%016llx "
           "differing_blocks=%u wet_nonzero=%u reset_nonzero=%u\n",
           (unsigned long long)first.initial_hash,
           (unsigned long long)first.retained_hash,
           (unsigned long long)first.reset_hash,
           first.different_blocks,first.retained_nonzero,
           first.reset_nonzero);
    return 0;
}
